// Command goef-linqgen generates typed bindings for marked GoLINQ declarations.
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"
)

const generatedHeader = "// Code generated by goef-linqgen; DO NOT EDIT.\n"

func main() {
	if err := run(os.Args[1:], os.Stderr); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(args []string, diagnostics io.Writer) error {
	flags := flag.NewFlagSet("goef-linqgen", flag.ContinueOnError)
	flags.SetOutput(diagnostics)
	source := flags.String("source", "", "Go file containing marked query and model declarations")
	output := flags.String("output", "", "generated Go file in the source directory")
	check := flags.Bool("check", false, "check freshness without writing")
	if err := flags.Parse(args); err != nil {
		if errors.Is(err, flag.ErrHelp) {
			return nil
		}
		return err
	}
	if flags.NArg() != 0 || !goFileName(*source) || !goFileName(*output) {
		return errors.New("goef-linqgen: specify -source and -output with ordinary .go file names")
	}
	sourcePath, err := filepath.Abs(*source)
	if err != nil {
		return err
	}
	outputPath, err := filepath.Abs(*output)
	if err != nil {
		return err
	}
	if filepath.Dir(sourcePath) != filepath.Dir(outputPath) || sourcePath == outputPath {
		return errors.New("goef-linqgen: source and output must be different files in the same directory")
	}

	sourceInfo, err := os.Lstat(sourcePath)
	if err != nil {
		return err
	}
	if !sourceInfo.Mode().IsRegular() {
		return fmt.Errorf("%s: source must be a regular file", *source)
	}
	input, err := os.ReadFile(sourcePath)
	if err != nil {
		return err
	}
	want, err := generate(*source, lf(input))
	if err != nil {
		return err
	}

	outputInfo, err := os.Lstat(outputPath)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	if outputInfo != nil {
		if !outputInfo.Mode().IsRegular() || os.SameFile(sourceInfo, outputInfo) {
			return fmt.Errorf("%s: output must be a separate regular file", *output)
		}
		have, err := os.ReadFile(outputPath)
		if err != nil {
			return err
		}
		have = lf(have)
		switch {
		case bytes.Equal(have, want):
			return nil
		case *check:
			return fmt.Errorf("%s: generated binding for %s is stale; regenerate it", *output, *source)
		case !bytes.HasPrefix(have, []byte(generatedHeader)):
			return fmt.Errorf("%s: refusing to overwrite a file without the goef-linqgen header", *output)
		}
	} else if *check {
		return fmt.Errorf("%s: generated binding for %s is missing; generate it", *output, *source)
	}
	return writeOutput(outputPath, want)
}

func goFileName(path string) bool {
	name := filepath.Base(path)
	return strings.HasSuffix(name, ".go") && !strings.HasSuffix(name, "_test.go") &&
		!strings.HasPrefix(name, ".") && !strings.HasPrefix(name, "_")
}

func lf(source []byte) []byte {
	return bytes.ReplaceAll(source, []byte("\r\n"), []byte("\n"))
}

func writeOutput(path string, contents []byte) error {
	f, err := os.CreateTemp(filepath.Dir(path), ".goef-linqgen-*")
	if err != nil {
		return err
	}
	defer os.Remove(f.Name())
	if _, err := f.Write(contents); err != nil {
		f.Close()
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	return os.Rename(f.Name(), path)
}
